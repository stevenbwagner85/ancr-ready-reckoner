#!/usr/bin/env python3
"""Build the AnCR ready reckoner.

Produces two files in the repository root from the sources in src/:
  ancr-ready-reckoner.html           the single-file offline tool
  AnCR-ready-reckoner-template.xlsx  the blank Excel template

The workbook is generated by the same JavaScript that the HTML tool uses for
its export, run here with macOS's built-in JavaScriptCore shell (or node).
"""
import base64, io, os, shutil, subprocess, sys, zipfile

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, 'src')
JSC = '/System/Library/Frameworks/JavaScriptCore.framework/Versions/Current/Helpers/jsc'


def read(*parts):
    with open(os.path.join(ROOT, *parts), encoding='utf-8') as f:
        return f.read()


def b64(*parts):
    with open(os.path.join(ROOT, *parts), 'rb') as f:
        return base64.b64encode(f.read()).decode('ascii')


def run_js(source):
    """Run a script that prints a hex string; return the decoded bytes."""
    tmp = os.path.join(ROOT, '.build-tmp.js')
    node = shutil.which('node')
    with open(tmp, 'w', encoding='utf-8') as f:
        f.write(('var print = console.log;\n' if node else '') + source)
    try:
        out = subprocess.run([node or JSC, tmp], check=True, capture_output=True, text=True).stdout
    finally:
        os.remove(tmp)
    return bytes.fromhex(out.strip())


def main():
    assets = 'ANCR.ASSETS = {logoNavy: "%s"};\n' % b64('assets', 'brunel-logo-navy-block.png')
    core = '\n'.join([read('src', 'model.js'), assets, read('src', 'zip.js'), read('src', 'workbook.js')])

    xlsx = run_js(core + '''
var bytes = ANCR.buildWorkbook(ANCR.emptyState()), hex = [];
for (var i = 0; i < bytes.length; i++) hex.push((bytes[i] < 16 ? '0' : '') + bytes[i].toString(16));
print(hex.join(''));
''')
    # The JavaScript writer stores parts uncompressed; compress the published template.
    src, packed = zipfile.ZipFile(io.BytesIO(xlsx)), io.BytesIO()
    with zipfile.ZipFile(packed, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as out:
        for info in src.infolist():
            out.writestr(zipfile.ZipInfo(info.filename, date_time=(2026, 1, 1, 0, 0, 0)), src.read(info.filename),
                         compress_type=zipfile.ZIP_DEFLATED)
    xlsx = packed.getvalue()
    with open(os.path.join(ROOT, 'AnCR-ready-reckoner-template.xlsx'), 'wb') as f:
        f.write(xlsx)

    html = read('src', 'app.html')
    html = html.replace('/*__CSS__*/', read('src', 'app.css'))
    html = html.replace('/*__JS__*/', (core + '\n' + read('src', 'app.js')).replace('</script', '<\\/script'))
    html = html.replace('__LOGO_WHITE__', 'data:image/png;base64,' + b64('assets', 'brunel-logo-white-block.png'))
    html = html.replace('__CALSS_WHITE__', 'data:image/png;base64,' + b64('assets', 'calss-name-white.png'))
    with open(os.path.join(ROOT, 'ancr-ready-reckoner.html'), 'w', encoding='utf-8') as f:
        f.write(html)
    print('Built template (%d bytes) and HTML tool (%d bytes)' % (len(xlsx), len(html.encode('utf-8'))))


if __name__ == '__main__':
    sys.exit(main())
